export function t(locale: Locale, key: string): string {
  return messages[locale][key] ?? messages.en[key] ?? key;
}

/**
 * 数量 + 单位：中文无复数；英文按 n===1 取单数键。
 * one/many 都是 i18n key，便于两种语言共用同一套模板。
 */
export function tn(locale: Locale, n: number, one: string, many: string): string {
  const key = locale === "zh" ? many : n === 1 ? one : many;
  return `${n} ${t(locale, key)}`;
}
